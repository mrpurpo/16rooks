"""Export a move list as a Typst table.

Columns "N.º" and "Movimiento", colour labels "B" (blancas, white) and "N"
(negras, black), with the moves split into `cols` blocks side by side
(column-major: block 1 holds moves 1..rows, block 2 the next rows, ...).
"""

from __future__ import annotations

import math

from .board import WHITE, Board, BoardError
from .checker import check_moves
from .pieces import Piece


def labelled_moves(board: Board, piece: Piece, moves) -> list[tuple[str, str]]:
    """[(label, "a1-b3"), ...]; the colour of each move comes from a replay."""
    res = check_moves(board, piece, moves)
    if res.error_index is not None:
        raise BoardError(f"cannot export an illegal sequence: {res.error}")
    return [("B" if col == WHITE else "N", f"{board.name(s)}-{board.name(d)}")
            for col, (s, d) in zip(res.colours, moves)]


def typst_table(items: list[tuple[str, str]], cols: int = 4, caption: str | None = None) -> str:
    n = len(items)
    rows = max(1, math.ceil(n / cols))
    lines = []
    for r in range(rows):
        cells = []
        for c in range(cols):
            i = c * rows + r
            if i < n:
                label, mv = items[i]
                cells.append(f"[{i + 1}], [`{label} {mv}`]")
            else:
                cells.append("[], []")
        lines.append("    " + ", ".join(cells) + ",")
    header = ", ".join(["[*N.º*], [*Movimiento*]"] * cols)
    table = "\n".join([
        "table(",
        f"    columns: {cols * 2},",
        f"    align: ({', '.join(['right, left'] * cols)}),",
        "    stroke: none,",
        "    inset: (x: 5pt, y: 3.5pt),",
        "    table.hline(stroke: 0.8pt),",
        f"    table.header({header}),",
        "    table.hline(stroke: 0.4pt),",
        *lines,
        "    table.hline(stroke: 0.8pt),",
        "  )",
    ])
    body = f"#figure(\n  {table},\n  caption: [{caption}],\n)" if caption else "#" + table
    return f"// {n} moves -- generated by swaprows export\n{body}\n"


def appendix_tuples(items: list[tuple[str, str]], cols: int = 4) -> str:
    """The `move-table((("B", "a1-a3"), ...), cols: 4)` call used in the paper's
    appendix (paper/sections/apendice.typ)."""
    lines = []
    for i in range(0, len(items), 4):
        lines.append("    " + " ".join(f'("{c}", "{m}"),' for c, m in items[i:i + 4]))
    return "#move-table(\n  (\n" + "\n".join(lines) + f"\n  ),\n  cols: {cols},\n)\n"
